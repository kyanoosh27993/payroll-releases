"""ساخت فایل «تغییرات برنامه.txt» — تاریخچه نسخه‌ها با قالب‌بندی درست RTL/فارسی+انگلیسی"""
import re, unicodedata

RLM = '\u200f'  # Right-to-Left Mark

LATIN = re.compile(r'[A-Za-z0-9._\-/()+%]+')

def rtl_line(line: str) -> str:
    """هر سطر را برای نمایش درست فارسی+انگلیسی در Notepad/ویرایشگرهای ساده آماده می‌کند."""
    if not line.strip():
        return line
    # اگر سطر با کاراکتر LTR (لاتین) شروع شود، RLM در ابتدا قرار می‌گیرد
    out = line
    # بعد از هر رشته لاتین که مستقیماً به کاراکتر فارسی/علامت فارسی می‌رسد، RLM
    def repl(m):
        nxt = out[m.end():m.end() + 1] or ''
        return m.group(0) + RLM if re.search(r'[^\x00-\x7F]', nxt) else m.group(0)
    out = LATIN.sub(repl, out)
    # اگر سطر با لاتین شروع می‌شود، RLM در ابتدا تا جهت پاراگراف RTL شود
    if re.match(r'^[A-Za-z0-9]', out):
        out = RLM + out
    return out

