/** نرمال‌سازی سبک برای راهنما (بدون وابستگی به موتور اصلی) */
function norm(s: string): string {
  return (s ?? '')
    .replace(/[۰-۹]/g, (d) => String('۰۱۲۳۴۵۶۷۸۹'.indexOf(d)))
    .replace(/[٠-٩]/g, (d) => String('٠١٢٣٤٥٦٧٨٩'.indexOf(d)))
    .replace(/\u200c/g, ' ')
    .replace(/[?؟!.,،؛:«»()\[\]]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

/** آیا پرسش از نوع «چگونه کار کنم» است؟ */
export function isGuideIntent(q: string): boolean {
  const s = norm(q);
  return /چطور|چگونه|چطوری|چجوری|چه طوری|نحوه|راهنمایی|آموزش|کجا|چی کار|چیکار|چه کار|میتونم|می توانم|ببینم|اصلاح کنم|وارد شم|پیدا کنم|اضافه کنم چیزی|چند قدم/.test(s);
}

const NORM_TOPICS = GUIDE_TOPICS.map((t) => ({
  topic: t,
  kws: t.keywords.map((k) => ({ raw: k, n: norm(k), wc: k.trim().split(/\s+/).length })),
}));

/** بهترین موضوع راهنما برای پرسش — یا null */
export function matchGuideTopic(question: string): GuideTopic | null {
  const q = norm(question);
  let best: GuideTopic | null = null;
  let bestScore = 0;
  for (const { topic, kws } of NORM_TOPICS) {
    let score = 0;
    for (const kw of kws) {
      if (q.includes(kw.n)) {
        // تطبیق پیوسته عبارت — امتیاز کامل
        score += kw.wc * 3 + Math.min(kw.n.length, 18) / 3;
      } else if (kw.wc > 1) {
        // تطبیق پراکنده: همه کلمات کلیدواژه در پرسش باشند (ترتیب مهم نیست)
        const words = kw.n.split(' ');
        if (words.every((w) => q.includes(w))) score += kw.wc * 1.5 + 1;
      }
    }
    if (score > bestScore) {
      bestScore = score;
      best = topic;
    }
  }
  // حداقل آستانه: یک کلیدواژه دوسطبی یا دو کلیدواژه یک‌کلمه‌ای
  return bestScore >= 4 ? best : null;
}

/** متن پاسخ راهنما */
export function guideAnswerText(topic: GuideTopic): string {
  const steps = topic.steps.map((s, i) => `${i + 1}) ${s}`).join('\n');
  return [
    topic.summary,
    '',
    'مراحل:',
    steps,
  ].join('\n');
}
